"""Vendor pinned Adobe horizontal CMaps into a reproducible runtime archive.

Requires the GitHub CLI for public, commit-pinned source reads. Cached files
are checked against Git blob hashes from that commit before every generation.
"""
import argparse
import base64
from concurrent.futures import ThreadPoolExecutor
import hashlib
import io
import json
from pathlib import Path
import re
import subprocess
import time
import zipfile

COMMIT = "f5cf3bca7fdfeaceb77aa82847e974f2306c20b4"
REPOSITORY = "adobe-type-tools/cmap-resources"


def api(path, repository=REPOSITORY):
    for attempt in range(3):
        try:
            return json.loads(subprocess.check_output(["gh", "api", f"repos/{repository}/{path}"]))
        except subprocess.CalledProcessError:
            if attempt == 2:
                raise
            time.sleep(attempt + 1)


def blob_hash(data):
    return hashlib.sha1(f"blob {len(data)}\0".encode() + data).hexdigest()


def generate(cache, target):
    tree = api(f"git/trees/{COMMIT}?recursive=1")
    assert not tree.get("truncated")
    entries = [entry for entry in tree["tree"] if entry["type"] == "blob" and (
        len(entry["path"].split("/")) == 3 and entry["path"].split("/")[1] == "CMap"
        and not entry["path"].endswith("-V") and entry["path"].split("/")[-1] != "V"
    )]
    license_entry = next(entry for entry in tree["tree"] if entry["path"] == "LICENSE.md")

    def fetch(entry):
        path = cache / entry["path"]
        data = path.read_bytes() if path.exists() else b""
        if blob_hash(data) != entry["sha"]:
            response = api(f"contents/{entry['path']}?ref={COMMIT}")
            data = base64.b64decode(response["content"], validate=False)
            assert response["sha"] == entry["sha"]
            assert blob_hash(data) == entry["sha"], entry["path"]
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        return entry, data

    with ThreadPoolExecutor(max_workers=6) as executor:
        resources = list(executor.map(fetch, entries))
    _, license_bytes = fetch(license_entry)
    records = []
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        for entry, data in sorted(resources, key=lambda pair: pair[0]["path"].split("/")[-1]):
            assert re.search(rb"/WMode\s+0\s+def", data), entry["path"]
            assert re.search(rb"/CMapType\s+1\s+def", data), entry["path"]
            name = entry["path"].split("/")[-1]
            ordering = re.search(rb"/Ordering\s+\(([^)]+)\)", data)[1].decode("ascii")
            registry = re.search(rb"/Registry\s+\(([^)]+)\)", data)[1].decode("ascii")
            assert registry == "Adobe"
            info = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            archive.writestr(info, data, compresslevel=9)
            records.append({"name": name, "ordering": ordering, "path": entry["path"],
                            "git_blob_sha1": entry["sha"], "sha256": hashlib.sha256(data).hexdigest(), "bytes": len(data)})
    assert len({record["name"] for record in records}) == len(records)
    target.mkdir(parents=True, exist_ok=True)
    payload = buffer.getvalue()
    (target / "horizontal.zip").write_bytes(payload)
    (target / "manifest.json").write_text(json.dumps({"repository": REPOSITORY, "commit": COMMIT,
        "archive_sha256": hashlib.sha256(payload).hexdigest(), "resources": records}, indent=2) + "\n")
    (target / "NOTICE").write_text(f"Adobe CMap resources\nSource: https://github.com/{REPOSITORY}/tree/{COMMIT}\n"
        "Unmodified horizontal CMap source files, compressed for inclusion in the native library.\n"
        "Each archived resource also retains its original copyright and license header.\n\n" + license_bytes.decode())
    (target / "names.rs").write_text("// Generated by scripts/generate_adobe_cmaps.py; do not edit.\n"
        "pub(super) const NAMES: &[(&str, &str)] = &[\n" + "".join(
            f'    ("{record["name"]}", "{record["ordering"]}"),\n' for record in records) + "];\n")
    print(f"Packaged {len(records)} horizontal CMaps: {sum(record['bytes'] for record in records)} -> {len(payload)} bytes")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cache", type=Path, default=Path("/tmp/ofdrw-adobe-cmap-sources"))
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] / "crates/ofdrw/assets/cmaps")
    args = parser.parse_args()
    generate(args.cache, args.output)
