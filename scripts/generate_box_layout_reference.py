"""Generate measured-box coordinates with the pinned sibling Java OFDRW build.

Build Java first: mvn -pl ofdrw-layout -am package -DskipTests
The Rust implementation is never called by this reference generator.
"""

from pathlib import Path
import os
import subprocess
import tempfile


ROOT = Path(__file__).resolve().parents[1]
JAVA = ROOT.parent
SOURCE = r"""
import java.util.*;
import org.ofdrw.layout.*;
import org.ofdrw.layout.element.*;
import org.ofdrw.layout.engine.*;

public class BoxLayoutReference {
    static Div box(double w, double h, AFloat f, Clear c) {
        return new Div(w, h).setFloat(f).setClear(c);
    }
    static void emit(String name, Div... boxes) {
        PageLayout page = new PageLayout(20d, 20d).setMargin(2d);
        List<Div> source = Arrays.asList(boxes);
        List<Segment> segments = new SegmentationEngine(page).process(source);
        List<VirtualPage> pages = new StreamingLayoutAnalyzer(page).analyze(segments);
        for (int index = 0; index < pages.size(); index++) {
            for (Div b : pages.get(index).getContent()) {
                int sourceIndex = -1;
                for (int i = 0; i < boxes.length; i++) {
                    if (boxes[i].getWidth().equals(b.getWidth())) sourceIndex = i;
                }
                Rectangle size = b.box();
                System.out.printf(java.util.Locale.ROOT, "%s\t%d\t%d\t%.9f\t%.9f\t%.9f\t%.9f%n",
                    name, index, sourceIndex, b.getX(), b.getY(), size.getWidth(), size.getHeight());
            }
        }
    }
    public static void main(String[] args) {
        emit("left_right", box(4,3,AFloat.left,Clear.none), box(5,7,AFloat.right,Clear.none), box(3,2,AFloat.left,Clear.none));
        emit("center", box(4,3,AFloat.center,Clear.none), box(3,4,AFloat.center,Clear.none));
        emit("clear", box(4,3,AFloat.left,Clear.none), box(5,4,AFloat.left,Clear.left), box(3,2,AFloat.right,Clear.none));
        emit("split", box(4,22,AFloat.left,Clear.both));
        emit("decoration", box(4,5,AFloat.left,Clear.both).setMargin(1d).setBorder(1d).setPadding(1d));
        emit("split_decoration", box(4,15,AFloat.left,Clear.both).setMargin(1d).setBorder(1d).setPadding(1d));
    }
}
"""


def main():
    classes = JAVA / "ofdrw-layout/target/classes"
    if not classes.is_dir():
        raise SystemExit("Build the sibling Java ofdrw-layout module first")
    classpath = os.pathsep.join(str(p) for p in [
        *sorted(JAVA.glob("*/target/classes")),
    ])
    with tempfile.TemporaryDirectory(prefix="ofdrw-box-reference-") as directory:
        source = Path(directory) / "BoxLayoutReference.java"
        source.write_text(SOURCE)
        def args_file(name, args):
            path = Path(directory) / name
            path.write_text("\n".join('"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'
                                      for value in args))
            return "@" + str(path)
        subprocess.run(["javac", args_file("compile.args", ["-proc:none", "-cp", classpath, str(source)])], check=True)
        result = subprocess.run(["java", args_file("run.args", ["-cp", directory + os.pathsep + classpath,
                                  "BoxLayoutReference"])], check=True, capture_output=True, text=True)
    fixture = ROOT / "crates/ofdrw/tests/fixtures/box-layout-java.tsv"
    revision = subprocess.run(["git", "-C", str(JAVA), "rev-parse", "HEAD"], check=True, capture_output=True, text=True).stdout.strip()
    fixture.write_text("# Generated by scripts/generate_box_layout_reference.py using Java OFDRW.\n"
                       f"# Java revision: {revision}\n"
                       "# case page source_index x y outer_width outer_height\n" + result.stdout)
    print(fixture.relative_to(ROOT))


if __name__ == "__main__":
    main()
