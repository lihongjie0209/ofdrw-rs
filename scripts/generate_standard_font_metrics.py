"""Extract compact core-font metrics from the pinned Apache PDFBox 2.0.29 JAR.

Usage: python generate_standard_font_metrics.py /path/to/pdfbox-2.0.29.jar
Only glyph names, advances and Symbol/ZapfDingbats encoding names are retained.
"""
import hashlib
from pathlib import Path
import sys
from zipfile import ZipFile

ROOT = Path(__file__).resolve().parents[1]
JAR_SHA256 = "69728a41a6e9feb98399560a31c1fe1b6467a66d1a8e33e677da24fda9263937"
PREFIX = "org/apache/pdfbox/resources/"
FONTS = ["Courier", "Courier-Bold", "Courier-Oblique", "Courier-BoldOblique",
         "Helvetica", "Helvetica-Bold", "Helvetica-Oblique", "Helvetica-BoldOblique",
         "Times-Roman", "Times-Bold", "Times-Italic", "Times-BoldItalic", "Symbol", "ZapfDingbats"]


def generate(path):
    assert hashlib.sha256(path.read_bytes()).hexdigest() == JAR_SHA256, "Wrong source JAR"
    lines = ["// Generated by scripts/generate_standard_font_metrics.py; do not edit.",
             "// Modified from Adobe core 14 AFMs: only names, widths and encoding codes retained.",
             "// Source: Apache PDFBox 2.0.29, SHA256 " + JAR_SHA256,
             "// Copyright and permission notices: assets/core14/NOTICE.", ""]
    notices = set()
    metrics = {}
    with ZipFile(path) as archive:
        for font in FONTS:
            text = archive.read(PREFIX + "afm/" + font + ".afm").decode("ascii")
            for line in text.splitlines():
                if line.startswith("Comment Copyright") or line.startswith("Notice "):
                    notices.add(line.removeprefix("Comment ").removeprefix("Notice "))
            glyphs = {}
            codes = {}
            for line in text.splitlines():
                if not line.startswith("C "):
                    continue
                fields = dict(field.strip().split(maxsplit=1) for field in line.split(";") if field.strip())
                name, width, code = fields["N"], int(fields["WX"]), int(fields["C"])
                assert name not in glyphs and 0 <= width <= 10000
                glyphs[name] = width
                if 0 <= code <= 255:
                    assert code not in codes
                    codes[code] = name
            metrics[font] = (glyphs, codes)
        lines.append("pub(super) const FONTS: &[(&str, &[(&str, u16)])] = &[")
        for font, (glyphs, _) in metrics.items():
            lines.append(f'    ("{font}", &[')
            lines.extend(f'        ("{name}", {width}),' for name, width in sorted(glyphs.items()))
            lines.append("    ]),")
        lines.append("];\n")
        for font, constant in [("Symbol", "SYMBOL_CODES"), ("ZapfDingbats", "DINGBATS_CODES")]:
            lines.append(f"pub(super) const {constant}: [Option<&str>; 256] = [")
            codes = metrics[font][1]
            lines.extend(f'    Some("{codes[code]}"),' if code in codes else "    None," for code in range(256))
            lines.append("];\n")
        dingbats = archive.read(PREFIX + "glyphlist/zapfdingbats.txt").decode("ascii")
        mapping = dict(line.split(";") for line in dingbats.splitlines() if line and not line.startswith("#"))
        lines.append("pub(super) const DINGBATS: &[(&str, char)] = &[")
        lines.extend(f'    ("{name}", \'\\u{{{code}}}\'),' for name, code in sorted(mapping.items()))
        lines.append("];\n")
        license_text = archive.read("META-INF/LICENSE").decode("utf-8")
        afm_notice = license_text.split("Adobe Font Metrics (AFM) for PDF Core 14 Fonts", 1)[1].split("CMaps for PDF Fonts", 1)[0]
        glyph_notice = dingbats.split("# Name:", 1)[0]
    target = ROOT / "crates/ofdrw/src/pdf_import/standard_font_data.rs"
    target.write_text("\n".join(lines))
    notice = ROOT / "crates/ofdrw/assets/core14/NOTICE"
    notice.parent.mkdir(parents=True, exist_ok=True)
    notice.write_text("Adobe Core 14 font metrics\n\n"
        "Derived from the AFM and glyph-list resources in Apache PDFBox 2.0.29.\n"
        "Modified: compact Rust lookup tables retain glyph names, widths and encoding codes.\n"
        "Source: https://archive.apache.org/dist/pdfbox/2.0.29/\n\n"
        + "\n".join(sorted(notices)) + "\n\n"
        + "Adobe Font Metrics (AFM) for PDF Core 14 Fonts" + afm_notice
        + "ITC Zapf Dingbats Glyph List\n\n" + glyph_notice)
    print("Generated metrics for", len(metrics), "fonts")


if __name__ == "__main__":
    generate(Path(sys.argv[1]))
